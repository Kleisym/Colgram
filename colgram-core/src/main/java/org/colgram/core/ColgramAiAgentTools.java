    /**
     * Extracts Python code from Koliti's reply, validates basic structure, and installs it live via ColgramPluginManager.
     */
    public static InstalledPluginResult extractAndInstallPlugin(String assistantReply, boolean actuallyInstall) {
        if (assistantReply == null || assistantReply.isEmpty()) {
            return new InstalledPluginResult(false, "", "", "");
        }
        Matcher m = PYTHON_FENCE.matcher(assistantReply);
        if (!m.find()) {
            return new InstalledPluginResult(false, "", "", "");
        }
        String code = m.group(1).trim();
        if (code.length() < 24 || (!code.contains("def ") && !code.contains("class "))) {
            return new InstalledPluginResult(false, "", "", "");
        }

        String name = extractStringConst(code, "__name__");
        String cmd = extractStringConst(code, "__command__");
        if (name == null || name.isEmpty()) {
            name = (cmd != null && !cmd.isEmpty()) ? ("Koliti " + cmd) : "Koliti Custom Plugin";
        }
        String baseSlug = (cmd != null && !cmd.isEmpty()) ? ("koliti_" + cmd) : ("koliti_" + sanitizeAsciiSlug(name));
        String fileName = baseSlug + ".py";

        // Ensure metadata headers exist so ColgramPluginManager indexes name & command cleanly.
        if (!code.contains("__name__")) {
            code = "__name__ = \"" + name.replace("\"", "'") + "\"\n"
                    + "__author__ = \"Koliti AI\"\n"
                    + "__version__ = \"1.0\"\n\n" + code;
        }

        boolean ok = true;
        if (actuallyInstall) {
            ok = ColgramPluginManager.installPlugin(fileName, code);
        }
        return new InstalledPluginResult(ok, fileName, name, cmd != null ? cmd : "");
    }

