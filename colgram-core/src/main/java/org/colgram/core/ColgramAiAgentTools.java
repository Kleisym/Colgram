    public static String extractNaturalMessageFromReply(String rawReply) {
        if (rawReply == null || rawReply.trim().isEmpty()) return "";
        String stripped = stripToolTags(rawReply).trim();
        if (stripped.isEmpty()) return "";
        // First check if the model quoted the exact message inside «...» or "..."
        Matcher quoted = Pattern.compile("«([^»]{2,400})»|\"([^\"]{2,400})\"").matcher(stripped);
        if (quoted.find()) {
            String candidate = quoted.group(1) != null ? quoted.group(1).trim() : quoted.group(2).trim();
            if (!candidate.isEmpty() && !looksLikeOfflineOrCannotSendRefusal(candidate)) {
                return candidate;
            }
        }
        String cleaned = ColgramAiContextEngine.extractCleanDraftText(stripped);
        cleaned = cleaned.replaceFirst("(?iu)^(?:я\\s+написал|написал|отправил|отправляю|сообщение\\s+для|текст\\s+для)[^:\\n]{0,48}[:\\-]\\s*", "").trim();
        return cleanMessagePayload(cleaned);
    }

