    private static String extractStringConst(String code, String varName) {
        Matcher m = Pattern.compile("^" + varName + "\\s*=\\s*[\"']([^\"'\\n]+)[\"']", Pattern.MULTILINE).matcher(code);
        return m.find() ? m.group(1).trim() : null;
    }

    private static String sanitizeAsciiSlug(String s) {
        StringBuilder sb = new StringBuilder();
        String low = s.toLowerCase(Locale.ROOT);
        for (int i = 0; i < low.length(); i++) {
            char c = low.charAt(i);
            if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) sb.append(c);
            else if (sb.length() > 0 && sb.charAt(sb.length() - 1) != '_') sb.append('_');
        }
        String out = sb.toString().replaceAll("^_+|_+$", "");
        return out.isEmpty() ? ("plugin_" + (System.currentTimeMillis() % 10000L)) : out;
    }

    private static boolean containsAny(String haystack, String... needles) {
        for (String n : needles) {
            if (haystack.contains(n)) return true;
        }
        return false;
    }
