    /**
     * Recognizes natural Russian/English person-directed messaging intents:
     * - "напиши kleisym и спроси как у него дела" -> target="Kleisym", sendNow=true
     * - "спроси у клейсима как дела" -> target="Kleisym", sendNow=true
     * - "передай kleisym что я скоро буду" -> target="Kleisym", sendNow=true
     * - "напиши ему" / "напиши ему ещё раз" (when lastReferencedTarget="Kleisym") -> target="Kleisym", sendNow=true
     */
    public static NaturalSendIntent parseNaturalMessagingIntent(
            String rawQuery,
            String lastReferencedTarget,
            String dialogDirectory
    ) {
        if (rawQuery == null || rawQuery.trim().isEmpty()) {
            return new NaturalSendIntent(false, "", false, false, "");
        }
        String q = rawQuery.trim();
        String ql = q.toLowerCase(Locale.ROOT);
        if (looksLikePluginCreationRequest(ql)) {
            return new NaturalSendIntent(false, "", false, false, "");
        }
        if (containsAny(ql, "в поле ввода", "в полю ввода", "в этот чат", "в этом чате", "сюда в чат")) {
            return new NaturalSendIntent(false, "", false, false, "");
        }
        boolean explicitDraftOnly = containsAny(ql, "черновик", "в поле ввода", "не отправляй", "только вставь", "просто вставь");
        boolean sendNow = !explicitDraftOnly;

        // 1. Pronoun follow-up referencing last known target (e.g. "ну и пофиг всеровно напиши ему", "отправь ему")
        if (lastReferencedTarget != null && !lastReferencedTarget.trim().isEmpty() && q.length() <= 140) {
            Matcher pm = PRONOUN_SEND_FOLLOWUP.matcher(q);
            if (pm.find()) {
                String canonical = resolveBestTargetFromDirectory(lastReferencedTarget, dialogDirectory);
                return new NaturalSendIntent(true, canonical.isEmpty() ? lastReferencedTarget : canonical, sendNow, true, "");
            }
        }

        // 2. "спроси у <target> ..." / "узнай у <target> ..."
        Matcher am = ASK_PERSON_SEND.matcher(q);
        if (am.find()) {
            String rawTarget = cleanChatTarget(am.group(1));
            if (!isNonPersonWord(rawTarget)) {
                String canonical = resolveBestTargetFromDirectory(rawTarget, dialogDirectory);
                boolean matchedDir = !canonical.isEmpty();
                if (matchedDir || rawTarget.startsWith("@") || hasLatinLetters(rawTarget) || rawTarget.length() >= 3) {
                    return new NaturalSendIntent(true, matchedDir ? canonical : rawTarget, sendNow, false, "");
                }
            }
        }

        // 3. "напиши <target> и спроси как у него дела" / "передай <target> что ..."
        Matcher cm = PERSON_COMPOUND_SEND.matcher(q);
        if (cm.find()) {
            String rawTarget = cleanChatTarget(cm.group(1));
            if (!isNonPersonWord(rawTarget)) {
                String canonical = resolveBestTargetFromDirectory(rawTarget, dialogDirectory);
                boolean matchedDir = !canonical.isEmpty();
                if (matchedDir || rawTarget.startsWith("@") || hasLatinLetters(rawTarget) || rawTarget.length() >= 3) {
                    return new NaturalSendIntent(true, matchedDir ? canonical : rawTarget, sendNow, false, "");
                }
            }
        }

        // 4. Direct unquoted person message matching a real dialog from directory (or explicit @username):
        //    e.g. "напиши kleisym привет как дела" / "напиши клейсиму привет" / "напиши @kleisym ку"
        Matcher dm = DIRECT_PERSON_UNQUOTED.matcher(q);
        if (dm.find()) {
            String rawTarget = cleanChatTarget(dm.group(2));
            String rest = dm.group(3) != null ? dm.group(3).trim() : "";
            if (!isNonPersonWord(rawTarget) && !rest.isEmpty()) {
                String canonical = resolveBestTargetFromDirectory(rawTarget, dialogDirectory);
                boolean matchedDir = !canonical.isEmpty();
                if (matchedDir || rawTarget.startsWith("@")) {
                    String literal = looksLikeGenerativeMessageRequest(rest) || looksLikeIndirectInstruction(rest)
                            ? ""
                            : cleanMessagePayload(rest);
                    return new NaturalSendIntent(true, matchedDir ? canonical : rawTarget, sendNow, false, literal);
                }
            }
        }

        // 5. English person/chat send: "send to Kleisym hello", "message Saved Messages hi", "ask Kleisym how are you"
        Matcher em = EN_PERSON_SEND.matcher(q);
        if (em.find()) {
            String rawTarget = cleanChatTarget(em.group(1));
            String rest = em.group(2) != null ? em.group(2).trim() : "";
            if ("saved".equalsIgnoreCase(rawTarget) && rest.toLowerCase(Locale.ROOT).startsWith("messages")) {
                rawTarget = "Saved Messages";
                rest = rest.length() > 8 ? rest.substring(8).trim() : "";
            }
            if (!isNonPersonWord(rawTarget)) {
                String canonical = resolveBestTargetFromDirectory(rawTarget, dialogDirectory);
                if (!canonical.isEmpty() || "Saved Messages".equalsIgnoreCase(rawTarget) || rawTarget.startsWith("@")) {
                    String resolvedName = !canonical.isEmpty() ? canonical : ("Saved Messages".equalsIgnoreCase(rawTarget) ? "Избранное" : rawTarget);
                    String literal = rest.isEmpty() || rest.toLowerCase(Locale.ROOT).startsWith("how ") || rest.toLowerCase(Locale.ROOT).startsWith("if ")
                            ? "" : cleanMessagePayload(rest);
                    return new NaturalSendIntent(true, resolvedName, sendNow, false, literal);
                }
            }
        }

        return new NaturalSendIntent(false, "", false, false, "");
    }

    private static boolean looksLikeIndirectInstruction(String rest) {
        if (rest == null || rest.isEmpty()) return false;
        String l = rest.toLowerCase(Locale.ROOT);
        return containsAny(l, "спроси", "узнай", "поинтересуйся", "как у него", "как у неё", "как у нее",
                "чтобы он", "чтобы она", "поздравь", "пожелай", "напомни", "объясни ему", "объясни ей",
                "от моего имени", "вежливо", "по-дружески");
    }

    private static boolean hasLatinLetters(String s) {
        if (s == null) return false;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) return true;
        }
        return false;
    }

    /**
     * Parses canonical dialog names & usernames from the compact dialogDirectory text and returns the
     * best matching canonical dialog title if score >= 0.72 (supports Cyrillic <-> Latin transliteration,
     * Russian case endings like "клейсиму" -> "Kleisym", and edit distance <= 2).
     */
    public static String resolveBestTargetFromDirectory(String rawTarget, String dialogDirectory) {
        if (rawTarget == null || rawTarget.trim().isEmpty() || dialogDirectory == null || dialogDirectory.isEmpty()) {
            return "";
        }
        String bestTitle = "";
        double bestScore = 0.0;
        String[] lines = dialogDirectory.split("\n");
        for (String line : lines) {
            String t = line.trim();
            if (!t.startsWith("• ") && !t.startsWith("- ")) continue;
            String body = t.substring(2).trim();
            int bracketIdx = body.indexOf(" [");
            String head = bracketIdx > 0 ? body.substring(0, bracketIdx).trim() : body;
            String title = head;
            String username = "";
            int atOpen = head.indexOf(" (@");
            if (atOpen > 0) {
                title = head.substring(0, atOpen).trim();
                int atClose = head.indexOf(')', atOpen + 3);
                if (atClose > atOpen + 3) {
                    username = head.substring(atOpen + 3, atClose).trim();
                }
            }
            double score = scoreTargetMatch(rawTarget, title, username);
            if (score > bestScore) {
                bestScore = score;
                bestTitle = title;
            }
        }
        return bestScore >= 0.72 ? bestTitle : "";
    }

    /**
     * Scores how well a user-spoken target (e.g. "клейсиму", "kleisym", "@kleisym", "избраном")
     * matches a real Telegram dialog title + username (0.0 .. 1.0).
     */
    public static double scoreTargetMatch(String rawQuery, String candidateTitle, String candidateUsername) {
        if (rawQuery == null || rawQuery.trim().isEmpty()) return 0.0;
        String q = rawQuery.startsWith("@") ? rawQuery.substring(1).trim() : rawQuery.trim();
        String ql = q.toLowerCase(Locale.ROOT);
        String tl = candidateTitle == null ? "" : candidateTitle.trim().toLowerCase(Locale.ROOT);
        String ul = candidateUsername == null ? "" : candidateUsername.trim().toLowerCase(Locale.ROOT);
        if (ul.startsWith("@")) ul = ul.substring(1);

        if (!tl.isEmpty() && tl.equals(ql)) return 1.0;
        if (!ul.isEmpty() && ul.equals(ql)) return 1.0;

        String qNorm = normalizeAlphaNum(ql);
        String tNorm = normalizeAlphaNum(tl);
        String uNorm = normalizeAlphaNum(ul);
        if (qNorm.isEmpty()) return 0.0;
        if (qNorm.equals(tNorm) || (!uNorm.isEmpty() && qNorm.equals(uNorm))) return 0.98;

        String qStem = stripRussianNameEnding(qNorm);
        String qLat = transliterateRuToLat(qNorm);
        String qStemLat = transliterateRuToLat(qStem);
        String tLat = transliterateRuToLat(tNorm);
        String uLat = transliterateRuToLat(uNorm);

        double best = 0.0;
        best = Math.max(best, scorePair(qNorm, tNorm));
        best = Math.max(best, scorePair(qStem, tNorm));
        best = Math.max(best, scorePair(qLat, tLat));
        best = Math.max(best, scorePair(qStemLat, tLat));
        if (!uNorm.isEmpty()) {
            best = Math.max(best, scorePair(qNorm, uNorm));
            best = Math.max(best, scorePair(qStem, uNorm));
            best = Math.max(best, scorePair(qLat, uLat));
            best = Math.max(best, scorePair(qStemLat, uLat));
        }
        return best;
    }

    private static double scorePair(String q, String cand) {
        if (q == null || cand == null || q.length() < 2 || cand.length() < 2) return 0.0;
        if (q.equals(cand)) return 0.96;
        if (cand.startsWith(q) && q.length() >= 3) return 0.90;
        if (cand.contains(q) && q.length() >= 3) return 0.86;
        if (q.contains(cand) && cand.length() >= 4) return 0.84;
        // Also compare individual words of multi-word titles (e.g. "Steal An Egg")
        String qSimple = simplifyPhoneticLat(q);
        String cSimple = simplifyPhoneticLat(cand);
        if (qSimple.equals(cSimple)) return 0.94;
        if (cSimple.startsWith(qSimple) && qSimple.length() >= 3) return 0.88;
        int maxLen = Math.max(qSimple.length(), cSimple.length());
        if (maxLen >= 4) {
            int dist = levenshtein(qSimple, cSimple);
            int allowed = maxLen >= 7 ? 2 : 1;
            if (dist <= allowed) {
                return 0.85 - (dist * 0.06);
            }
        }
        return 0.0;
    }

    /** Collapses common Russian-to-Latin phonetic ambiguities (y/i, c/k, w/v, ph/f, double letters) for fuzzy name matching. */
    private static String simplifyPhoneticLat(String s) {
        if (s == null || s.isEmpty()) return "";
        String x = s.replace("ph", "f").replace("ck", "k").replace("ch", "c").replace("sh", "s")
                .replace("kh", "h").replace("ye", "e").replace("ya", "a").replace("yu", "u").replace("yo", "o")
                .replace('y', 'i').replace('j', 'i').replace('w', 'v').replace('q', 'k').replace('z', 's');
        StringBuilder sb = new StringBuilder(x.length());
        char prev = 0;
        for (int i = 0; i < x.length(); i++) {
            char c = x.charAt(i);
            if (c != prev) {
                sb.append(c);
                prev = c;
            }
        }
        return sb.toString();
    }

